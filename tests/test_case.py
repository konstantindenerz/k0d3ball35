@pytest.mark.skipif(openscad() is None, reason="openscad not installed")
@pytest.mark.parametrize("half", ["left", "right"])
def test_render_lid_plates(tmp_path, half, data):
    """The two plates: disjoint, together the closed lid, knuckles alternating along the pin,
    the pin hole on the axis, the stop faces leaning by tent_deg, the fold free of collisions."""
    import numpy as np

    sx = -1 if half == "left" else 1
    meshes, values = {}, None
    for part in ("lid", "lid_outer", "lid_inner", "lid_folded", "lid_folded_free"):
        out = tmp_path / f"{part}-{half}.stl"
        # one degree short of the stop the plates must not touch anywhere; at the stop the two
        # faces coincide, which is not a manifold union, so only the volume is checked there
        extra = {"hinge_fold_override": 20} if part == "lid_folded_free" else None
        values, log = run_scad(part.replace("_free", ""), half, out, extra)
        assert "WARNING" not in log and "ERROR" not in log, part
        meshes[part] = mesh_of(out)
        if part != "lid_folded":
            assert meshes[part].is_watertight, part
    hx, az = values["hinge_x"] * sx, values["hinge_axis_z"]
    r_k = values["hinge_knuckle_d"] / 2
    vol = {k: m.volume for k, m in meshes.items()}
    # The two plates have to add up to the closed lid. They overlap by a sliver at the stop
    # faces, and the sliver grows with the fold: 0.03 mm3 at the 33 degree fold of r2.2, 0.64 at
    # the 58 degree fold the moved pocket forces. That is 0.0014 % of the lid and a cross
    # section of 0.008 mm2 along the hinge - two orders below a 0.2 mm layer, so it prints as
    # nothing. A real mis-cut (a knuckle in the wrong plate, a groove left solid) is cubic
    # millimetres to tens of them, which this still catches.
    overlap = vol["lid_outer"] + vol["lid_inner"] - vol["lid"]
    assert -0.5 < overlap < 1.0, f"plates overlap or leave material out by {overlap:.3f} mm3"
    assert abs(vol["lid_outer"] + vol["lid_inner"] - vol["lid_folded"]) < 0.5, "folded plates collide"
    assert abs(vol["lid_outer"] + vol["lid_inner"] - vol["lid_folded_free"]) < 0.5, "folded plates collide"
    assert vol["lid_outer"] > 0.3 * vol["lid"] and vol["lid_inner"] > 0.3 * vol["lid"]
    n_seg, seg = int(values["hinge_segments"]), values["hinge_seg"]
    gap = (values["hinge_y1"] - values["hinge_y0"] - n_seg * seg) / (n_seg - 1)
    y0 = values["hinge_y0"]
    for part, parity, side in (("lid_outer", 0, 1), ("lid_inner", 1, -1)):
        v = meshes[part].vertices
        # nothing crosses the hinge line further than the knuckle radius
        assert ((v[:, 0] - hx) * side * sx).min() >= -r_k - 0.01, part
        d = np.hypot(v[:, 0] - hx, v[:, 2] - az)
        # knuckle surfaces only over this plate's segments (the roof top plane is left out: a
        # roof corner next to the cut sits on the knuckle radius by coincidence)
        ys = v[(np.abs(d - r_k) < 0.02) & (v[:, 2] < values["lid_top_z"] - 0.01)][:, 1]
        assert len(ys) > 100, part
        own = [(y0 + i * (seg + gap), y0 + i * (seg + gap) + seg) for i in range(n_seg) if i % 2 == parity]
        # (the two end knuckles run 0.5 mm into the skirt, hence the tolerance)
        assert all(any(a - 0.6 <= y <= b + 0.6 for a, b in own) for y in ys), part
        # the pin hole runs along the axis
        hole = v[np.abs(d - (values["hinge_pin_d"] + 0.2) / 2) < 0.02]
        assert len(hole) > 100, part
        # the stop faces: planes through the axis leaning outward by hinge_stop_deg below it
        m = meshes[part]
        t = values["hinge_stop_deg"]
        want = np.array([-np.cos(np.radians(t)) * side * sx, 0, -np.sin(np.radians(t))])
        stop = m.area_faces[np.linalg.norm(m.face_normals - want, axis=1) < 0.01]
        assert stop.sum() > 60.0, (part, stop.sum())


