# ----------------------------------------------------------------- floor dxf
def _dxf_loops(path):
    ezdxf = pytest.importorskip("ezdxf")
    doc = ezdxf.readfile(str(path))
    loops = []
    for e in doc.modelspace():
        if e.dxftype() == "LWPOLYLINE":
            pts = [(p[0], p[1]) for p in e.get_points()]
            xs, ys = [p[0] for p in pts], [p[1] for p in pts]
            loops.append((min(xs), max(xs), min(ys), max(ys)))
        elif e.dxftype() == "CIRCLE":
            c, r = e.dxf.center, e.dxf.radius
            loops.append((c.x - r, c.x + r, c.y - r, c.y + r))
    return loops


def _holes(loops, d=2.2, tol=0.1):
    return sorted(((b[0] + b[1]) / 2, (b[2] + b[3]) / 2) for b in loops
                  if abs(b[1] - b[0] - d) < tol and abs(b[3] - b[2] - d) < tol)


def test_floor_dxf_right():
    loops = _dxf_loops(CASE / "dxf" / "floor-right.dxf")
    holes = _holes(loops)
    for hx, hy in HOLES + CASE_SCREWS:
        assert any(abs(x - hx) < 0.05 and abs(y - hy) < 0.05 for x, y in holes), (hx, hy)
    pocket = [b for b in loops if abs(b[1] - b[0] - 30.0) < 0.05 and abs(b[3] - b[2] - 30.0) < 0.05]
    assert len(pocket) == 1, "30 x 30 pocket outline (housing 29 x 29 plus 0.5 mm clearance)"
    cradle = _dxf_loops(CRADLE / "dxf" / "floor-19mm-pocket.dxf")
    outer = max(cradle, key=lambda b: b[1] - b[0])
    for i, off in enumerate((BALL[0], BALL[0], BALL[1], BALL[1])):
        assert abs(pocket[0][i] - (outer[i] + off)) < 0.05, i


def test_floor_dxf_left_is_mirrored():
    loops = _dxf_loops(CASE / "dxf" / "floor-left.dxf")
    holes = _holes(loops)
    for hx, hy in HOLES:
        assert any(abs(x + hx) < 0.05 and abs(y - hy) < 0.05 for x, y in holes), (hx, hy)
    assert not [b for b in loops if abs(b[1] - b[0] - 31.0) < 0.05], "no pocket on the left"
