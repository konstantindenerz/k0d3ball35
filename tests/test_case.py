@pytest.mark.skipif(openscad() is None, reason="openscad not installed")
@pytest.mark.parametrize("half", ["left", "right"])
def test_render_tray(tmp_path, half, data):
    import numpy as np

    out = tmp_path / f"tray-{half}.stl"
    values, log = run_scad("tray", half, out)
    assert "WARNING" not in log and "ERROR" not in log
    assert out.stat().st_size > 100_000
    mesh = mesh_of(out)
    assert mesh.is_watertight
    v = mesh.vertices
    sx = -1 if half == "left" else 1
    assert abs(v[:, 2].min() - values["base_z"]) < 0.05
    assert abs(v[:, 2].max() - values["box_top_z"]) < 0.05
    # standoff rings just below the PCB underside: insert hole 3.2 in a 6.0 standoff
    for hx, hy in HOLES:
        hx *= sx
        near = v[(np.hypot(v[:, 0] - hx, v[:, 1] - hy) < 3.5) & (v[:, 2] > -PCB_T - 0.05) & (v[:, 2] < -PCB_T + 0.05)]
        r = np.hypot(near[:, 0] - hx, near[:, 1] - hy)
        assert len(near) > 40, (hx, hy)
        assert abs(r.min() - values["insert_hole_d"] / 2) < 0.02, (hx, hy, r.min())
        assert abs(r.max() - values["standoff_d"] / 2) < 0.4, (hx, hy, r.max())
        # the insert hole ends with at least 1.5 mm of floor below it
        column = v[(np.hypot(v[:, 0] - hx, v[:, 1] - hy) < values["insert_hole_d"] / 2 + 0.1) & (v[:, 2] > values["base_z"] + 0.01)]
        bottom = column[:, 2].min()
        assert abs(bottom - (-PCB_T - values["insert_depth"])) < 0.05, (hx, hy, bottom)
        assert bottom - values["base_z"] >= 1.5
    # foot magnet pockets from below at the generated positions, nothing in the rim
    bottom = circle_centres(v, values["base_z"] + 2.4)
    expected = [(x * sx, y) for x, y in data["foot_magnets"][half]]
    assert len(bottom) == 4 and same_points(bottom, expected), (bottom, expected)
    for mx, my in expected:
        ring = v[(np.hypot(v[:, 0] - mx, v[:, 1] - my) < 3.5) & (np.abs(v[:, 2] - (values["base_z"] + 2.4)) < 0.02)]
        assert abs(np.hypot(ring[:, 0] - mx, ring[:, 1] - my).max() - 3.1) < 0.05
    assert circle_centres(v, values["rim_z"] - 2.4) == []
    # a smooth outer wall: the footprint just below the rim stays inside outline plus wall (no pads)
    layout = load_layout(half)
    hull = layout.outline.buffer(3.2 + 0.3, join_style=2)
    if half == "right":
        hull = hull.union(Point(BALL).buffer(16.0 + 0.3)).union(layout.housing_footprint().buffer(0.3))
    band = v[np.abs(v[:, 2] - (values["rim_z"] - 0.5)) < 0.6]
    assert len(band) > 0
    assert all(hull.contains(Point(x * sx, y)) for x, y, _ in band), half
    if half == "right":
        # case screw holes through the pocket floor, counterbored from below
        for cx, cy in CASE_SCREWS:
            near = v[(np.hypot(v[:, 0] - cx, v[:, 1] - cy) < 2.0) & (np.abs(v[:, 2] - values["pocket_floor_z"]) < 0.05)]
            assert len(near) > 10, (cx, cy)
            assert abs(np.hypot(near[:, 0] - cx, near[:, 1] - cy).max() - 1.1) < 0.05
            cb = v[(np.hypot(v[:, 0] - cx, v[:, 1] - cy) < 3.0) & (np.abs(v[:, 2] - (values["base_z"] + 0.5)) < 0.05)]
            assert len(cb) > 10, "counterbore leaves 2 mm of floor"
        # nothing of the tray inside the cradle circle above the PCB plane
        above = v[v[:, 2] > -PCB_T + 0.05]
        assert np.hypot(above[:, 0] - BALL[0], above[:, 1] - BALL[1]).min() >= 14.0
        # pocket floor exists at -11.6 under the housing
        floor = v[(np.abs(v[:, 2] - values["pocket_floor_z"]) < 0.02) & (np.abs(v[:, 0] - BALL[0]) < 15) & (np.abs(v[:, 1] - BALL[1]) < 14.5)]
        assert len(floor) > 4
    else:
        assert np.hypot(v[:, 0] - BALL[0], v[:, 1] - BALL[1]).min() < 20 or True   # left half has no pocket
        assert values["has_ball"] == 0


