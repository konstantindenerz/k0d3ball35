def test_stack_json(stack, cradle_stack):
    assert {"left", "right", "right-25mm"} <= set(stack)
    for name, v in stack.items():
        assert v["pocket_floor_z"] == cradle_stack["floor_z"], name
        assert abs(v["standoff_h"] - (-PCB_T - v["floor_z_key"])) < 1e-6, name
        assert v["floor_z_key"] <= -PCB_T - 3.0, "3 mm under the PCB for sockets and diodes"
        assert v["base_z"] <= v["well_floor_z"] - 2.0 and v["base_z"] <= v["pocket_floor_z"] - 2.0, name
        assert v["box_roof_under_z"] >= 5.7 + 1.0, name
        assert v["box_top_z"] > v["box_roof_under_z"], name
        assert v["rim_z"] < cradle_stack["rim_z"], "pocket wall must stay below the cup rim"
        assert v["lid_roof_under_z"] >= 11.0 + 1.0, name
        assert v["lid_top_z"] > v["lid_roof_under_z"], name
        assert v["insert_hole_d"] == 3.2 and v["standoff_d"] == 6.0, name
        assert v["standoff_d"] - v["insert_hole_d"] >= 2 * 1.4, "1.4 mm around the insert"
        assert v["foot_magnets"] == 4, name
        assert abs(v["lid_top_z"] - (v["lid_roof_under_z"] + 3.0)) < 1e-6, name
        assert abs(v["lid_lift"] - (v["lid_top_z"] - v["rim_z"] + v["lid_lip_depth"])) < 1e-6, name
    assert stack["left"]["has_ball"] == 0 and stack["right"]["has_ball"] == 1
    r = stack["right"]
    assert r["lid_roof_under_z"] >= cradle_stack["ball_top_above_pcb_top"] + 1.0
    assert r["housing_x"] == cradle_stack["housing_x"] and r["housing_y"] == cradle_stack["housing_y"]
    assert r["case_screw_sp"] == cradle_stack["case_screw_sp"]
    assert r["ball_top_z"] == cradle_stack["ball_top_above_pcb_top"]
    assert abs(r["cradle_rim_z"] - cradle_stack["rim_z"]) < 1e-6
    assert stack["right-25mm"]["lid_roof_under_z"] >= 23.05 + 1.0


