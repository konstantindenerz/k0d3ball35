def openscad():
    for cand in (shutil.which("openscad"), "/Applications/OpenSCAD.app/Contents/MacOS/OpenSCAD"):
        if cand and Path(cand).exists():
            return cand
    return None


def run_scad(part, half, out, extra=None):
    cmd = [openscad(), "--backend", "manifold", "-D", f'part="{part}"', "-D", f'half="{half}"']
    for k, v in (extra or {}).items():
        cmd += ["-D", f'{k}="{v}"' if isinstance(v, str) else f"{k}={v}"]
    cmd += ["-o", str(out), str(SCAD)]
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    assert res.returncode == 0, res.stderr
    log = res.stderr + res.stdout
    values = {m.group(1): float(m.group(2)) for m in re.finditer(r'STACK (\w+)=(-?[\d.]+)', log)}
    return values, log


def parse_data(text: str) -> dict:
    """data.scad arrays -> python: {name: {half: value}}."""
    data: dict = {}
    for m in re.finditer(r"^(\w+)_(left|right) = (.*);$", text, re.M):
        name, half, value = m.groups()
        data.setdefault(name, {})[half] = json.loads(value)
    return data


