def mesh_of(path):
    trimesh = pytest.importorskip("trimesh")
    # drop the zero-area triangles with a repeated vertex that the manifold export leaves where
    # the hinge grooves meet the strip; they would break is_watertight although the solid is fine
    mesh = trimesh.load(path, force="mesh")
    f = mesh.faces
    mesh.update_faces((f[:, 0] != f[:, 1]) & (f[:, 1] != f[:, 2]) & (f[:, 0] != f[:, 2]))
    return mesh


def circle_centres(v, z, tol=0.02, max_r=3.5, rings_only=False):
    """Centres of vertex clusters lying on the plane z (magnet pocket floors / ceilings). The
    mean of the points within max_r + 0.5 of the running centre, iterated from a seed on the
    rim, walks to the circle's centre even when a neighbouring circle is only a few mm away.

    With `rings_only` a cluster counts only if it really is a full circle of constant radius.
    An assembly cuts other edges through the same plane - a lid skirt, a hinge knuckle, a stray
    vertex - and those would otherwise be reported as pockets that are not there."""
    import numpy as np

    pts = v[np.abs(v[:, 2] - z) < tol][:, :2]
    centres = []
    while len(pts):
        c = pts[0]
        for _ in range(12):
            near = pts[np.hypot(pts[:, 0] - c[0], pts[:, 1] - c[1]) < max_r + 0.5]
            c = near.mean(axis=0)
        ring = pts[np.hypot(pts[:, 0] - c[0], pts[:, 1] - c[1]) < max_r + 0.5]
        r = np.hypot(ring[:, 0] - c[0], ring[:, 1] - c[1])
        if not rings_only or (len(ring) >= 32 and r.max() - r.min() < 0.2):
            centres.append(tuple(c))
        pts = pts[np.hypot(pts[:, 0] - c[0], pts[:, 1] - c[1]) >= max_r + 0.5]
    return sorted((round(x, 1), round(y, 1)) for x, y in centres)


def same_points(a, b, tol=0.3):
    return len(a) == len(b) and all(any(abs(x - u) < tol and abs(y - w) < tol for u, w in b) for x, y in a)


