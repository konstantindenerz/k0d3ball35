def test_data_matches_layout(data):
    for half in ("left", "right"):
        layout = load_layout(half)
        outline = Polygon(data["outline"][half])
        assert outline.symmetric_difference(layout.outline).area < 0.05, half   # 3 decimals
        assert data["holes"][half] == [[h["x"], h["y"]] for h in layout.cfg["mounting_holes"]]
        assert Polygon(data["bay"][half]).symmetric_difference(layout.battery_bay()).area < 1e-3
        assert data["case_screws"][half] == [[x, y] for x, y in layout.case_screws()]
        assert data["has_ball"][half] == layout.has_ball
        parts = layout.back_parts()
        well = Polygon(data["well"][half])
        for name in ("J3", "RB1"):
            assert well.contains(parts[name].buffer(1.0 - 1e-3, join_style=2)), (half, name)
        assert well.contains(layout.battery_bay().buffer(1.0 - 1e-3, join_style=2)), half
        # foot magnets: four in the thick floor under the outer lid plate, clear of the wells, the
        # channel and the standoffs
        magnets = data["foot_magnets"][half]
        assert len(magnets) == 4
        # the hinge line has to clear the ball pocket, so on the ball half it follows the ball
        want = -13 if half == "left" else round(BALL[0] - 17.2 - 0.8, 1)
        assert data["hinge_x"][half] == want
        dx = data["foot_dx"][half]
        assert abs(dx - (layout.outline.bounds[0] - 3.2 - 3.0 - data["hinge_x"][half])) < 1e-3   # 3 decimals
        # in the lid roof: inside the outer plate, off the hinge strip and the ball window
        for x, y in magnets:
            lx = x - dx
            assert lx - 3.1 >= data["hinge_x"][half] + 6.0 + 0.5, "under the hinge strip"
            assert layout.outline.buffer(-3.0, join_style=2).contains(Point(lx, y).buffer(3.1)), (half, x, y)
            if layout.has_ball:
                assert Point(lx, y).distance(Point(BALL)) >= 8.0 + 3.1 + 1.0
        # every rubber foot fully on or fully off the outer plate as a foot
        plate_x1 = layout.outline.bounds[2] + 3.2 + dx
        assert all(abs(x - plate_x1) >= 10.5 / 2 + 0.5 for x, y in data["feet"][half]), half
        inner = layout.outline.buffer(-3.0, join_style=2)
        keep = [well.buffer(2.0, join_style=2)]
        if layout.has_ball:
            keep.append(layout.housing_box().buffer(2.5, join_style=2))
            keep.append(layout.fpc_box().buffer(2.0, join_style=2))
            if layout.cable_corridor() is not None:
                keep.append(layout.cable_corridor().buffer(2.0, join_style=2))
        for x, y in magnets:
            disc = Point(x, y).buffer(3.1)
            assert inner.contains(disc), (half, x, y)
            assert not any(disc.intersects(k) for k in keep), (half, x, y)
            assert all(Point(x, y).distance(Point(hx, hy)) >= 3.0 + 3.1
                       for hx, hy in HOLES + [HOLE5[half]]), (half, x, y)
        for i, a in enumerate(magnets):
            for b in magnets[i + 1:]:
                assert Point(a).distance(Point(b)) >= 8.0
        if layout.has_ball:
            assert Polygon(data["housing_footprint"][half]).symmetric_difference(layout.housing_footprint()).area < 0.05
            assert Polygon(data["housing_box"][half]).symmetric_difference(layout.housing_box()).area < 1e-3
            assert Polygon(data["notch"][half]).symmetric_difference(layout.notch_polygon()).area < 0.05
            assert data["ball_center"][half] == list(layout.ball_center)
        else:
            assert data["housing_footprint"][half] == [] and data["case_screws"][half] == []
    assert data["has_ball"]["left"] is False and data["has_ball"]["right"] is True
    # controller block rectangle: outer PCB edge to the key-side wall, top edge to the block bottom
    for half in ("left", "right"):
        x0, y0, x1, y1 = data["box_rect"][half]
        assert x0 == -71.5 and y0 == -4.75 and x1 == -45.5
        assert 45.0 <= y1 <= 57.65
        cx0, cy0, cx1, cy1 = data["ctrl_rect"][half]
        assert x0 < cx0 and cx1 < x1 and cy1 + 2 < y1


