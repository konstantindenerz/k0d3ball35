@pytest.mark.skipif(openscad() is None, reason="openscad not installed")
@pytest.mark.parametrize("half", ["left", "right"])
def test_render_lid(tmp_path, half, data):
    import numpy as np

    out = tmp_path / f"lid-{half}.stl"
    values, log = run_scad("lid", half, out)
    assert "WARNING" not in log and "ERROR" not in log
    assert out.stat().st_size > 100_000
    mesh = mesh_of(out)
    assert mesh.is_watertight
    v = mesh.vertices
    sx = -1 if half == "left" else 1
    assert abs(v[:, 2].min() - (values["rim_z"] - values["lid_lip_depth"])) < 0.02, "lip reaches into the tray"
    assert abs(v[:, 2].max() - values["lid_top_z"]) < 0.02
    # no vertex inside the controller box walls plus clearance below the box top
    x0, y0, x1, y1 = data["box_rect"][half]
    bx0, bx1 = sorted(((x0 - 3.5) * sx, (x1 + 3.5) * sx))
    inside = v[(v[:, 0] > bx0 + 0.01) & (v[:, 0] < bx1 - 0.01) & (v[:, 1] > y0 - 3.5 + 0.01) & (v[:, 1] < y1 + 3.5 - 0.01)
               & (v[:, 2] < values["box_top_z"] + 0.3 - 0.01)]
    assert len(inside) == 0, inside[:5]
    # the lip: a ring inside the cavity wall face, nowhere in the box or pocket regions
    layout = load_layout(half)
    cavity = layout.outline.buffer(0.2, join_style=2)
    outer_face = cavity.buffer(-0.15, join_style=2)
    inner_face = cavity.buffer(-0.15 - 1.0 - 0.05, join_style=2)
    z0 = values["rim_z"] - values["lid_lip_depth"]
    lip = v[(v[:, 2] > z0 + 0.45) & (v[:, 2] < values["rim_z"] - 0.02)]     # above the lead-in chamfer
    assert len(lip) > 40
    for x, y, _ in lip:
        p = Point(x * sx, y)
        assert outer_face.buffer(0.02).contains(p) and not inner_face.contains(p), (half, x, y)
        assert not Polygon([(x0, y0), (x1, y0), (x1, y1), (x0, y1)]).buffer(3.5 + 1.0 - 0.05, join_style=2).contains(p), (half, x, y)
        if layout.has_ball:
            assert p.distance(Point(BALL)) >= 14.0 + 1.0 - 0.05, (half, x, y)
    below = v[v[:, 2] < values["rim_z"] - 0.02]
    assert np.abs(below[:, 2] - (values["rim_z"] - values["lid_lip_depth"] / 2)).max() <= values["lid_lip_depth"] / 2 + 0.02
    # roof magnets from the roof underside, same xy as the tray floor pockets, roof top closed
    pockets = circle_centres(v, values["lid_roof_under_z"] + 2.4)
    expected = [(x * sx, y) for x, y in data["foot_magnets"][half]]
    assert len(pockets) == 4 and same_points(pockets, expected), (pockets, expected)
    assert circle_centres(v, values["lid_top_z"] - 0.3) == []
    top = v[np.abs(v[:, 2] - values["lid_top_z"]) < 0.02]
    assert all(np.hypot(top[:, 0] - mx, top[:, 1] - my).min() > 3.0 for mx, my in expected), "skin over the magnets"
    if half == "right":
        # the ball (plus 1 mm) stays clear of the lid
        centre = np.array([BALL[0], BALL[1], values["ball_top_z"] - BALL_D / 2])
        assert np.linalg.norm(v - centre, axis=1).min() >= BALL_D / 2 + 1.0
        assert values["lid_roof_under_z"] >= values["ball_top_z"] + 1.0
    # printed roof-down: no upward face below the roof top (the lip's stepped lead-in faces down)
    n, a, fz = mesh.face_normals, mesh.area_faces, mesh.triangles_center[:, 2]
    assert a[(n[:, 2] > 0.7) & (fz < values["lid_top_z"] - 0.1)].sum() < 5.0


