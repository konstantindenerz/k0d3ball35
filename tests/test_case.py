def test_logo_svg_matches_the_grid(logo):
    """The vector master is the same artwork as the cells the case is engraved with: rasterise
    it and compare cell by cell, so a broken path never reaches the silkscreen or the web."""
    import io

    import numpy as np

    cairosvg = pytest.importorskip("cairosvg")
    Image = pytest.importorskip("PIL.Image")
    nx, ny = logo["logo_grid"]
    ink_cells = {(x + i, y + j) for x, y, w, h in logo["logo_rects"]
                 for i in range(w) for j in range(h)}
    scale = 8
    w, h = nx * scale, round(ny * logo["logo_aspect"] * scale)
    png = cairosvg.svg2png(url=str(LOGO_SVG), output_width=w, output_height=h)
    ink = (np.array(Image.open(io.BytesIO(png)).convert("RGBA"))[:, :, 3] > 128).astype(int)
    cy = h / ny
    for j in range(ny):
        y0, y1 = round(j * cy + 3), round((j + 1) * cy - 3)
        for i in range(nx):
            filled = ink[y0:y1, i * scale + 2:i * scale + 6].mean() > 0.5
            assert filled == ((i, j) in ink_cells), f"cell ({i}, {j})"


def test_logo_grid(logo):
    """The wordmark is a grid of whole cells: the rectangles tile the ink exactly once."""
    nx, ny = logo["logo_grid"]
    assert (nx, ny) == (18, 35), "the artwork changed, check the render before committing"
    assert abs(logo["logo_aspect"] - 1.524) < 0.01, "cell height / width of the artwork"
    covered = set()
    for x, y, w, h in logo["logo_rects"]:
        assert 0 <= x and x + w <= nx and 0 <= y and y + h <= ny, (x, y, w, h)
        cells = {(i, j) for i in range(x, x + w) for j in range(y, y + h)}
        assert not cells & covered, f"rectangle {(x, y, w, h)} overlaps an earlier one"
        covered |= cells
    assert len(covered) == logo["logo_ink_cells"]
    # the frame closes: the foot mirrored in at the top matches the one at the bottom
    rows = [["#" if (i, j) in covered else "." for i in range(nx)] for j in range(ny)]
    assert rows[0] == rows[-1] and rows[1] == rows[-2], "the cropped top was not completed"


