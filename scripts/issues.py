"""Markdown ticket tracker for the issues/ folder.

Each ticket is one markdown file ``issues/<area>-<slug>.md`` with a YAML
frontmatter block. This script validates the frontmatter and renders the
index ``issues/README.md``.

Usage:
    scripts/issues.py            # regenerate issues/README.md
    scripts/issues.py --check    # validate only, exit 1 on problems
    scripts/issues.py --diff     # exit 1 if README.md is out of date
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ISSUES_DIR = ROOT / "issues"
INDEX = ISSUES_DIR / "README.md"

AREAS = ("hw", "fw", "mech", "doc", "test", "infra")
TYPES = ("feature", "bug", "question", "task")
PRIORITIES = ("P0", "P1", "P2", "P3")
STATUSES = ("open", "in-progress", "done", "wontfix")
REQUIRED = ("title", "type", "priority", "status", "area", "created")

FRONTMATTER_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)
SLUG_RE = re.compile(r"^(hw|fw|mech|doc|test|infra)-[a-z0-9]+(-[a-z0-9]+)*\.md$")


@dataclass
class Ticket:
    path: Path
    meta: dict[str, str]

    @property
    def slug(self) -> str:
        return self.path.stem

    def __getattr__(self, name: str) -> str:
        try:
            return self.meta[name]
        except KeyError as exc:  # pragma: no cover - defensive
            raise AttributeError(name) from exc


def parse_frontmatter(text: str) -> dict[str, str] | None:
    match = FRONTMATTER_RE.match(text)
    if not match:
        return None
    meta: dict[str, str] = {}
    for line in match.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            return None
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip().strip('"').strip("'")
    return meta


def load_tickets() -> tuple[list[Ticket], list[str]]:
    tickets: list[Ticket] = []
    problems: list[str] = []
    for path in sorted(ISSUES_DIR.glob("*.md")):
        if path.name == "README.md":
            continue
        rel = path.relative_to(ROOT)
        if not SLUG_RE.match(path.name):
            problems.append(f"{rel}: file name must match <area>-<slug>.md with area in {AREAS}")
        meta = parse_frontmatter(path.read_text(encoding="utf-8"))
        if meta is None:
            problems.append(f"{rel}: missing or malformed frontmatter")
            continue
        for key in REQUIRED:
            if key not in meta or not meta[key]:
                problems.append(f"{rel}: missing frontmatter field '{key}'")
        if meta.get("type") not in TYPES:
            problems.append(f"{rel}: type must be one of {TYPES}")
        if meta.get("priority") not in PRIORITIES:
            problems.append(f"{rel}: priority must be one of {PRIORITIES}")
        if meta.get("status") not in STATUSES:
            problems.append(f"{rel}: status must be one of {STATUSES}")
        if meta.get("area") not in AREAS:
            problems.append(f"{rel}: area must be one of {AREAS}")
        if meta.get("area") and not path.name.startswith(meta["area"] + "-"):
            problems.append(f"{rel}: file name prefix must equal area '{meta.get('area')}'")
        created = meta.get("created", "")
        try:
            date.fromisoformat(created)
        except ValueError:
            problems.append(f"{rel}: created must be an ISO date (YYYY-MM-DD)")
        tickets.append(Ticket(path, meta))
    return tickets, problems


def render_index(tickets: list[Ticket]) -> str:
    lines = [
        "# Issues",
        "",
        "Tickets for features, bugs, questions and tasks. One markdown file per ticket,",
        "see `spec/01-design-spec.md` section 7 for the convention.",
        "This index is generated by `scripts/issues.py`; do not edit it by hand.",
        "",
    ]
    counts = {s: sum(1 for t in tickets if t.status == s) for s in STATUSES}
    lines.append("| Status | Count |")
    lines.append("|--------|-------|")
    for status in STATUSES:
        lines.append(f"| {status} | {counts[status]} |")
    lines.append("")
    for status in STATUSES:
        group = [t for t in tickets if t.status == status]
        if not group:
            continue
        lines.append(f"## {status}")
        lines.append("")
        lines.append("| Priority | Ticket | Type | Area | Title | Created |")
        lines.append("|----------|--------|------|------|-------|---------|")
        group.sort(key=lambda t: (PRIORITIES.index(t.priority), t.slug))
        for t in group:
            lines.append(
                f"| {t.priority} | [{t.slug}]({t.path.name}) | {t.type} | {t.area} | {t.title} | {t.created} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="validate frontmatter only")
    parser.add_argument("--diff", action="store_true", help="fail if README.md is out of date")
    args = parser.parse_args(argv)

    tickets, problems = load_tickets()
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    if problems:
        return 1
    rendered = render_index(tickets)
    if args.check:
        print(f"ok: {len(tickets)} tickets valid")
        return 0
    if args.diff:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != rendered:
            print("error: issues/README.md is out of date, run scripts/issues.py", file=sys.stderr)
            return 1
        print("ok: issues/README.md up to date")
        return 0
    INDEX.write_text(rendered, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(ROOT)} ({len(tickets)} tickets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
